export function getProperty(id: string): Property | undefined {
  return properties.find((p) => p.id === id);
}

export interface PropertyFilters {
  transactionType?: string;
  city?: string;
  minPrice?: number;
  maxPrice?: number;
  beds?: number;
  baths?: number;
  propertyType?: string;
  county?: string;
  q?: string;
}

export function filterProperties(
  list: Property[],
  filters: PropertyFilters,
): Property[] {
  return list.filter((p) => {
    if (filters.transactionType && p.transactionType !== filters.transactionType)
      return false;
    if (
      filters.city &&
      !p.city.toLowerCase().includes(filters.city.toLowerCase()) &&
      !p.address.toLowerCase().includes(filters.city.toLowerCase())
    )
      return false;
    if (filters.county && p.county !== filters.county) return false;
    if (filters.minPrice && p.price < filters.minPrice) return false;
    if (filters.maxPrice && p.price > filters.maxPrice) return false;
    if (filters.beds && p.beds < filters.beds) return false;
    if (filters.baths && p.baths < filters.baths) return false;
    if (filters.propertyType && p.propertyType !== filters.propertyType) return false;
    if (filters.q) {
      const q = filters.q.toLowerCase();
      const hay = `${p.title} ${p.city} ${p.address} ${p.features.join(" ")}`.toLowerCase();
      if (!hay.includes(q)) return false;
    }
    return true;
  });
}
